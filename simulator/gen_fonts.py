#!/usr/bin/env python3
"""Generate simulator/js/gfxfonts.js from LovyanGFX's built-in GFX fonts.

The firmware draws with LovyanGFX's FreeSans / FreeSansBold fonts (Adafruit
GFXfont format).  So that text width, height and clipping in the simulator
match the device exactly, the sim renders from the very same glyph tables,
extracted here from LovyanGFX's own headers rather than approximated with a
browser font.

Run from the repo root after `pio run` has fetched LovyanGFX:
    python3 simulator/gen_fonts.py
The output is committed, so the sim works without the PlatformIO tree.
"""
import base64, os, re, sys

FONTS = [            # every GFX font the UI uses; add a size here, then re-run
    "FreeSans9pt7b",
    "FreeSans12pt7b",
    "FreeSansBold9pt7b",
    "FreeSansBold12pt7b",
    "FreeSansBold18pt7b",
]

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
GFXFF = os.path.join(REPO, ".pio", "libdeps", "cyd_new_ui_combined", "LovyanGFX",
                     "src", "lgfx", "Fonts", "GFXFF")
OUT = os.path.join(HERE, "js", "gfxfonts.js")
FONT16 = os.path.join(os.path.dirname(GFXFF), "Font16.h")   # LovyanGFX fonts::Font2


def preprocess(src):
    """Resolve the #ifdef/#ifndef/#else/#endif blocks in a font header, honouring
    the header's own #defines — enough for Font16.h's grave/dollar options."""
    defined, out, stack = set(), [], []
    for line in src.splitlines():
        t = line.strip()
        on = all(stack)
        if t.startswith("#ifdef"):   stack.append(t.split()[1] in defined); continue
        if t.startswith("#ifndef"):  stack.append(t.split()[1] not in defined); continue
        if t.startswith("#else"):    stack[-1] = not stack[-1]; continue
        if t.startswith("#endif"):   stack.pop(); continue
        if not on: continue
        if t.startswith("#define"):  defined.add(t.split()[1]); continue
        out.append(line)
    return "\n".join(out)


def parse_font2():
    """Font2 is a BMPfont: per-char width table + per-char row bitmaps, MSB-left,
    (width+6)>>3 bytes per row (LovyanGFX draws width-1 columns: 1px margin)."""
    src = preprocess(open(FONT16, encoding="utf-8").read())
    hgt = int(re.search(r"chr_hgt_f16\s+(\d+)", open(FONT16).read()).group(1))
    base = int(re.search(r"baseline_f16\s+(\d+)", open(FONT16).read()).group(1))
    wt = re.search(r"widtbl_f16\[96\]\s*=.*?\{(.*?)\};", src, re.S).group(1)
    wt = re.sub(r"//[^\n]*", "", wt)
    widths = [int(v) for v in re.findall(r"\d+", wt)]
    assert len(widths) == 96, len(widths)
    bitmap, offs = bytearray(), []
    for i in range(96):
        m = re.search(r"chr_f16_%02X\[\d+\]\s*=.*?\{(.*?)\};" % (0x20 + i), src, re.S)
        body = re.sub(r"//[^\n]*", "", m.group(1))
        offs.append(len(bitmap))
        bitmap += bytes(int(h, 16) for h in re.findall(r"0x[0-9A-Fa-f]{2}", body))
    return bitmap, offs, widths, hgt, base


def parse(name):
    src = open(os.path.join(GFXFF, name + ".h"), encoding="utf-8").read()
    bm = re.search(r"Bitmaps\[\]\s*PROGMEM\s*=\s*\{(.*?)\};", src, re.S).group(1)
    bitmap = bytes(int(h, 16) for h in re.findall(r"0x[0-9A-Fa-f]{2}", bm))
    gl = re.search(r"Glyphs\[\]\s*PROGMEM\s*=\s*\{(.*?)\}\s*;", src, re.S).group(1)
    glyphs = [tuple(int(v) for v in g)
              for g in re.findall(r"\{\s*(-?\d+),\s*(-?\d+),\s*(-?\d+),\s*(-?\d+),\s*(-?\d+),\s*(-?\d+)\s*\}", gl)]
    tail = re.search(r"GFXfont\s+" + name + r"\s*PROGMEM\s*=\s*\{.*?,\s*(0x[0-9A-Fa-f]+),\s*(0x[0-9A-Fa-f]+),\s*(\d+)\s*\}", src, re.S)
    first, last, y_adv = int(tail.group(1), 16), int(tail.group(2), 16), int(tail.group(3))
    assert len(glyphs) == last - first + 1, (name, len(glyphs), first, last)
    return bitmap, glyphs, first, last, y_adv


def main():
    if not os.path.isdir(GFXFF):
        sys.exit(f"LovyanGFX fonts not found at {GFXFF} — run `pio run -e cyd_new_ui_combined` first.")
    out = [
        "/* AUTO-GENERATED by simulator/gen_fonts.py from LovyanGFX's GFXFF headers —",
        " * do not edit.  Adafruit GFXfont tables: glyph = [bitmapOffset, width,",
        " * height, xAdvance, xOffset, yOffset]; bitmaps are base64, MSB-first,",
        " * rows packed continuously (not byte-aligned per row). */",
        "const GFX_FONTS = {};",
    ]
    for name in FONTS:
        bitmap, glyphs, first, last, y_adv = parse(name)
        out.append(f"GFX_FONTS.{name} = {{ first: {first}, last: {last}, yAdvance: {y_adv},")
        out.append(f"  bitmap: \"{base64.b64encode(bitmap).decode()}\",")
        out.append("  glyphs: [" + ",".join("[" + ",".join(map(str, g)) + "]" for g in glyphs) + "] };")
    bitmap, offs, widths, hgt, base = parse_font2()
    out.append(f"GFX_FONTS.Font2 = {{ bmp: true, first: 32, last: 127, height: {hgt}, baseline: {base},")
    out.append(f"  bitmap: \"{base64.b64encode(bytes(bitmap)).decode()}\",")
    out.append(f"  offsets: [{','.join(map(str, offs))}], widths: [{','.join(map(str, widths))}] }};")
    open(OUT, "w", encoding="utf-8").write("\n".join(out) + "\n")
    print(f"wrote {os.path.relpath(OUT, REPO)}: {', '.join(FONTS)}, Font2")


if __name__ == "__main__":
    main()
